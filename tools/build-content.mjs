// Extracts the study sections and the question bank from the original single-file
// prototype into server-only modules (so answers never ship to the browser).
import fs from 'node:fs';

const SRC = process.argv[2] || 'PL-300_Prepare-the-data.html';
const html = fs.readFileSync(SRC, 'utf8');

const TITLES = [
  'Get or connect to data',
  'Power Query Editor & profiling',
  'Clean the data',
  'Shape & transform tables',
  'Combine queries & build keys',
  'Performance, parameters & M',
];

const content = [];
const re = /<section class="screen[^"]*" data-part="(\d)">([\s\S]*?)<\/section>/g;
let m;
while ((m = re.exec(html))) {
  let body = m[2];
  const cut = body.indexOf('<div class="pager">');
  if (cut !== -1) body = body.slice(0, cut);
  content.push({ part: +m[1], title: TITLES[+m[1] - 1], html: body.trim() });
}
if (content.length !== 6) throw new Error('expected 6 sections, got ' + content.length);

const qs = html.indexOf('const Q=[');
const qe = html.search(/\];\s*const PASS/);
if (qs < 0 || qe < 0) throw new Error('question bank not found');
const bank = html.slice(qs + 'const Q='.length, qe + 1);

fs.writeFileSync('src/content.js',
  '// GENERATED by tools/build-content.mjs - do not edit by hand.\nexport const CONTENT = ' + JSON.stringify(content, null, 1) + ';\n');
fs.writeFileSync('src/questions.js',
  '// Server-only: contains the correct answers. Never import this from public/.\nexport const PART_TITLES = ' + JSON.stringify(TITLES) + ';\nexport const QUESTIONS = ' + bank + ';\n');
console.log('sections:', content.length, '| questions module written');
